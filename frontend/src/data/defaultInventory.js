export const INVENTORY_STORAGE_KEY = 'restaurant_inventory_v2';

export const getStoredInventory = () => {
  try {
    const raw = localStorage.getItem(INVENTORY_STORAGE_KEY);
    if (raw) {
      const parsed = JSON.parse(raw);
      if (Array.isArray(parsed) && parsed.length >= 60) {
        return parsed;
      }
    }
  } catch (e) {
    console.warn(e);
  }
  localStorage.setItem(INVENTORY_STORAGE_KEY, JSON.stringify(DEFAULT_INVENTORY));
  return DEFAULT_INVENTORY;
};

export const saveStoredInventory = (items) => {
  try {
    if (Array.isArray(items) && items.length > 0) {
      localStorage.setItem(INVENTORY_STORAGE_KEY, JSON.stringify(items));
    }
  } catch (e) {
    console.warn(e);
  }
};
